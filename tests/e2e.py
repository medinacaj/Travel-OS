def check(cond, msg):
    print(("  ok  " if cond else "  FAIL") + " " + msg)
    if not cond: failures.append(msg)

def route(page, rain=False):
    def handler(r):
        u = r.request.url
        if "leaflet.min.js" in u: return r.fulfill(path=os.path.join(LEAFLET, "leaflet.js"), content_type="application/javascript")
        if "leaflet.min.css" in u: return r.fulfill(path=os.path.join(LEAFLET, "leaflet.css"), content_type="text/css")
        if "api.open-meteo.com" in u:
            body = {"current": {"weather_code": 63 if rain else 1, "precipitation": 1.2 if rain else 0, "temperature_2m": 17.4}}
            return r.fulfill(json=body)
        if any(h in u for h in ["tile.openstreetmap", "opentopomap", "arcgisonline", "cartocdn"]):
            return r.fulfill(body=PNG, content_type="image/png")
        if u.startswith(BASE): return r.continue_()
        return r.abort()
    page.route("**/*", handler)

def count(page, sel): return page.locator(sel).count()

